// runac — the Runa compiler executable.
//
//     main.ru  →  runac  →  main.rbc
//
// Pipeline: Lexer → Parser → AST → Compiler → Bytecode.
// The compiler never executes anything (baseline spec, section 11).
//
// v0.9: runac resolves package declarations (import / as-import / cimport)
// through the ImportResolver, links every dependency unit into the output
// chunk and extracts RPR-embedded native packages into the native root (the
// output directory) so the VM can dlopen them at run time.
#include <fstream>
#include <iostream>
#include <memory>
#include <sstream>
#include <string>
#include <vector>

#include "ast/ast.hpp"
#include "bytecode/bytecode.hpp"
#include "compiler/compiler.hpp"
#include "errors/errors.hpp"
#include "import/importer.hpp"
#include "import/platform.hpp"
#include "lexer/lexer.hpp"
#include "parser/parser.hpp"
#include "tools/tool_common.hpp"

namespace {

void printUsage(std::ostream& out) {
    out << "Usage: runac <file.ru> [options]\n"
           "\n"
           "Compiles a Runa source file into Runa bytecode (.rbc).\n"
           "\n"
           "Options:\n"
           "  -o <file.rbc>    Output path (default: <input>.rbc next to the source)\n"
           "  --dump-tokens    Print the token stream (development aid)\n"
           "  --dump-ast       Print the abstract syntax tree (development aid)\n"
           "  --dump-bytecode  Print a disassembly of the generated bytecode\n"
           "  -h, --help       Show this help\n";
}

}  // namespace

int main(int argc, char** argv) {
    std::vector<std::string> args(argv + 1, argv + argc);
    std::string input;
    std::string output;
    bool dumpTokens = false;
    bool dumpAst = false;
    bool dumpBytecode = false;

    for (std::size_t i = 0; i < args.size(); ++i) {
        const std::string& arg = args[i];
        if (arg == "-h" || arg == "--help") {
            printUsage(std::cout);
            return 0;
        } else if (arg == "-o") {
            if (i + 1 >= args.size()) {
                std::cerr << "runac: missing path after -o\n";
                printUsage(std::cerr);
                return 2;
            }
            output = args[++i];
        } else if (arg == "--dump-tokens") {
            dumpTokens = true;
        } else if (arg == "--dump-ast") {
            dumpAst = true;
        } else if (arg == "--dump-bytecode") {
            dumpBytecode = true;
        } else if (!arg.empty() && arg[0] == '-') {
            std::cerr << "runac: unknown option '" << arg << "'\n";
            printUsage(std::cerr);
            return 2;
        } else if (input.empty()) {
            input = arg;
        } else {
            std::cerr << "runac: unexpected extra argument '" << arg << "'\n";
            return 2;
        }
    }

    if (input.empty()) {
        printUsage(std::cerr);
        return 2;
    }

    std::string source;
    if (!runa::tools::readFile(input, source, "runac")) return 2;
    if (output.empty()) output = runa::tools::defaultOutputPath(input);

    // Package search paths (documented precedence): the project's runalibs
    // directory first, then the toolchain's internal and external libraries
    // next to the executable — independent of the current working directory.
    const std::string projectRoot = runa::tools::dirnameOf(input);
    const std::string exeDir = runa::platform::executableDir();
    std::vector<std::string> searchPaths = {
        projectRoot + "/runalibs",
        exeDir + "/runalibs/internal",
        exeDir + "/runalibs/external",
    };
    runa::importer::ImportResolver resolver(searchPaths);

    try {
        // 1. Lexer: source → tokens (no semantic analysis).
        runa::lexer::Lexer lexer(source, input);
        std::vector<runa::lexer::Token> tokens = lexer.tokenize();
        if (dumpTokens) {
            std::cout << "== tokens ==\n";
            runa::lexer::dumpTokens(tokens, std::cout);
        }

        // 2. Parser: tokens → AST (syntax validation + structure).
        runa::parser::Parser parser(std::move(tokens));
        runa::ast::Program program = parser.parseProgram();
        if (dumpAst) {
            std::cout << "== ast ==\n";
            runa::ast::dump(program, std::cout);
        }

        // 3. Compiler: AST → bytecode (never executes the program).
        runa::compiler::CompileOptions options;
        options.projectRoot = projectRoot;
        options.nativeRoot = runa::tools::dirnameOf(output);
        options.resolver = &resolver;
        runa::compiler::Compiler compiler;
        runa::bytecode::Chunk chunk = compiler.compileProgram(program, options);
        if (dumpBytecode) {
            runa::bytecode::disassemble(chunk, std::cout);
        }

        // 4. Serialize the chunk into a .rbc file (format v4).
        std::ostringstream blob;
        runa::bytecode::serialize(chunk, blob);
        const std::string bytes = blob.str();

        std::ofstream out(output, std::ios::binary);
        if (!out) {
            std::cerr << "runac: cannot open output file '" << output << "'\n";
            return 2;
        }
        out.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
        out.close();
        if (!out) {
            std::cerr << "runac: failed to write '" << output << "'\n";
            return 2;
        }

        std::cout << "runac: wrote " << output << " (" << bytes.size() << " bytes)\n";
    } catch (const runa::errors::RunaErrorException& failure) {
        // Source context only makes sense for errors in the main source file;
        // package-internal errors carry their own file label and would show a
        // misleading line from the wrong file.
        const bool mainUnitError =
            failure.error().location.filename.empty() ||
            failure.error().location.filename == input;
        runa::errors::report(failure.error(), mainUnitError ? source : std::string());
        return 1;
    }
    return 0;
}
