// runa — combined command-line tool: compile + run in one step.
//
//     runa main.ru
//
// This is a convenience wrapper. Internally it uses exactly the same separate
// Compiler and VM components as `runac` / `runavm`, so the conceptual
// separation required by the baseline spec is preserved.
//
// v0.9: package declarations resolve through the same ImportResolver as
// runac; the native root is the source file's directory.
#include <iostream>
#include <memory>
#include <string>
#include <vector>

#include "ast/ast.hpp"
#include "compiler/compiler.hpp"
#include "errors/errors.hpp"
#include "import/importer.hpp"
#include "import/platform.hpp"
#include "lexer/lexer.hpp"
#include "parser/parser.hpp"
#include "runtime/runtime.hpp"
#include "tools/tool_common.hpp"
#include "vm/vm.hpp"

namespace {

void printUsage(std::ostream& out) {
    out << "Usage: runa <file.ru> [options]\n"
           "\n"
           "Compiles and executes a Runa source file in one step.\n"
           "Internally this uses the same separate Compiler and VM as runac/runavm.\n"
           "\n"
           "Options:\n"
           "  --dump-tokens    Print the token stream (development aid)\n"
           "  --dump-ast       Print the abstract syntax tree (development aid)\n"
           "  --dump-bytecode  Print a disassembly of the generated bytecode\n"
           "  --trace          Print every executed VM instruction (development aid)\n"
           "  --dump-globals   Print global variables after execution (development aid)\n"
           "  -h, --help       Show this help\n";
}

}  // namespace

int main(int argc, char** argv) {
    std::vector<std::string> args(argv + 1, argv + argc);
    std::string input;
    bool dumpTokens = false;
    bool dumpAst = false;
    bool dumpBytecode = false;
    bool trace = false;
    bool dumpGlobals = false;

    for (std::size_t i = 0; i < args.size(); ++i) {
        const std::string& arg = args[i];
        if (arg == "-h" || arg == "--help") {
            printUsage(std::cout);
            return 0;
        } else if (arg == "--dump-tokens") {
            dumpTokens = true;
        } else if (arg == "--dump-ast") {
            dumpAst = true;
        } else if (arg == "--dump-bytecode") {
            dumpBytecode = true;
        } else if (arg == "--trace") {
            trace = true;
        } else if (arg == "--dump-globals") {
            dumpGlobals = true;
        } else if (!arg.empty() && arg[0] == '-') {
            std::cerr << "runa: unknown option '" << arg << "'\n";
            printUsage(std::cerr);
            return 2;
        } else if (input.empty()) {
            input = arg;
        } else {
            std::cerr << "runa: unexpected extra argument '" << arg << "'\n";
            return 2;
        }
    }

    if (input.empty()) {
        printUsage(std::cerr);
        return 2;
    }

    std::string source;
    if (!runa::tools::readFile(input, source, "runa")) return 2;

    const std::string projectRoot = runa::tools::dirnameOf(input);
    const std::string exeDir = runa::platform::executableDir();
    std::vector<std::string> searchPaths = {
        projectRoot + "/runalibs",
        exeDir + "/runalibs/internal",
        exeDir + "/runalibs/external",
    };
    runa::importer::ImportResolver resolver(searchPaths);

    try {
        // 1. Lexer: source → tokens
        runa::lexer::Lexer lexer(source, input);
        std::vector<runa::lexer::Token> tokens = lexer.tokenize();
        if (dumpTokens) {
            std::cout << "== tokens ==\n";
            runa::lexer::dumpTokens(tokens, std::cout);
        }

        // 2. Parser: tokens → AST
        runa::parser::Parser parser(std::move(tokens));
        runa::ast::Program program = parser.parseProgram();
        if (dumpAst) {
            std::cout << "== ast ==\n";
            runa::ast::dump(program, std::cout);
        }

        // 3. Compiler: AST → bytecode (separate component)
        runa::compiler::CompileOptions options;
        options.projectRoot = projectRoot;
        options.nativeRoot = projectRoot;
        options.resolver = &resolver;
        runa::compiler::Compiler compiler;
        runa::bytecode::Chunk chunk = compiler.compileProgram(program, options);
        if (dumpBytecode) {
            runa::bytecode::disassemble(chunk, std::cout);
        }

        // 4. VM: bytecode → execution (separate component)
        runa::vm::Options vmOptions;
        vmOptions.trace = trace;
        vmOptions.nativeRoot = projectRoot;
        runa::vm::VirtualMachine vm(vmOptions);
        vm.run(chunk);
        if (dumpGlobals) {
            runa::runtime::printGlobals(vm.globals(), std::cout);
        }
    } catch (const runa::errors::RunaErrorException& failure) {
        const bool mainUnitError =
            failure.error().location.filename.empty() ||
            failure.error().location.filename == input;
        runa::errors::report(failure.error(), mainUnitError ? source : std::string());
        return 1;
    }
    return 0;
}
